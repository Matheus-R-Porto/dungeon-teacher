import fs from 'node:fs';
import path from 'node:path';
const version=JSON.parse(fs.readFileSync('package.json','utf8')).version;
const license=fs.readFileSync(`.logs/node-${process.version}-LICENSE.txt`);
const root=path.resolve(`release/DungeonMaster-Beta-${version}-Windows`);
if(fs.existsSync(root))throw Error('Export already exists; preserve it or choose a new destination.');
fs.mkdirSync(root,{recursive:true});
fs.cpSync(`release/beta-${version}/win-unpacked`,path.join(root,'Jogo'),{recursive:true});
const runtime=path.join(root,'Runtime');fs.mkdirSync(runtime);
fs.copyFileSync(process.execPath,path.join(runtime,'node.exe'));
fs.writeFileSync(path.join(runtime,'NODE-LICENSE.txt'),license);
fs.writeFileSync(path.join(runtime,'package.json'),JSON.stringify({private:true,type:'module',version}));
for(const dir of ['server','shared','src'])fs.cpSync(dir,path.join(runtime,dir),{recursive:true,filter:source=>!source.split(path.sep).includes('node_modules')});
fs.cpSync('server/node_modules/ws',path.join(runtime,'server/node_modules/ws'),{recursive:true});
fs.copyFileSync('desktop/local-playtest.mjs',path.join(runtime,'local-playtest.mjs'));
fs.copyFileSync('desktop/LEIA-ME.txt',path.join(root,'LEIA-ME.txt'));
fs.writeFileSync(path.join(root,'JOGAR TORRE LOCAL.cmd'),'@echo off\r\ncd /d "%~dp0"\r\n"Runtime\\node.exe" "Runtime\\local-playtest.mjs"\r\nif errorlevel 1 pause\r\n');
fs.writeFileSync(path.join(root,'JOGAR CAMPANHA.cmd'),'@echo off\r\nstart "Dungeon Master" "%~dp0Jogo\\DungeonMaster.exe"\r\n');
console.log(root);
